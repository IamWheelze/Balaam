#!/usr/bin/env python3
"""Generate videos with Google's Veo models through the Gemini API.

Commands:
  models                         list the Veo models your key can use
  generate PROMPT [options]      text-to-video or image-to-video
  extend CLIP.mp4 PROMPT         continue a clip that Veo generated
  stitch OUT.mp4 CLIP.mp4 ...    join clips into one video (ffmpeg)

The API key is read from GEMINI_API_KEY. In a cloud session whose environment
injects the key through the network proxy, the variable can be left unset.
"""

import argparse
import json
import mimetypes
import os
import pathlib
import subprocess
import sys
import tempfile
import time

from google import genai
from google.genai import types

DEFAULT_MODEL = os.environ.get("VEO_MODEL", "veo-3.1-generate-preview")
OUT_DIR = pathlib.Path(os.environ.get("VEO_OUT_DIR", "output"))
POLL_SECONDS = 10


def client() -> genai.Client:
    # Placeholder key: the cloud proxy replaces the header with the real one.
    return genai.Client(api_key=os.environ.get("GEMINI_API_KEY", "proxy-injected"))


def load_image(path: str) -> types.Image:
    mime = mimetypes.guess_type(path)[0] or "image/png"
    return types.Image(image_bytes=pathlib.Path(path).read_bytes(), mime_type=mime)


def wait(c: genai.Client, op):
    start = time.time()
    while not op.done:
        print(f"  generating... {int(time.time() - start)}s", file=sys.stderr, end="\r")
        time.sleep(POLL_SECONDS)
        op = c.operations.get(op)
    print(file=sys.stderr)
    if op.error:
        sys.exit(f"Veo error: {op.error}")
    videos = (op.response and op.response.generated_videos) or []
    if not videos:
        reason = getattr(op.response, "rai_media_filtered_reasons", None)
        sys.exit(f"No video returned. Filter reason: {reason or 'unknown'}")
    return videos


def save(c: genai.Client, videos, name: str, meta: dict) -> list[pathlib.Path]:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    paths = []
    for i, gv in enumerate(videos):
        suffix = f"_{i + 1}" if len(videos) > 1 else ""
        path = OUT_DIR / f"{name}{suffix}.mp4"
        c.files.download(file=gv.video)
        gv.video.save(str(path))
        # Sidecar keeps the server-side URI so the clip can be extended later.
        sidecar = dict(meta, video_uri=gv.video.uri)
        path.with_suffix(".json").write_text(json.dumps(sidecar, indent=2))
        paths.append(path)
        print(path)
    return paths


def default_name(prompt: str) -> str:
    slug = "".join(ch if ch.isalnum() else "-" for ch in prompt.lower())[:40].strip("-")
    return f"{time.strftime('%Y%m%d-%H%M%S')}-{slug or 'clip'}"


def build_config(a) -> types.GenerateVideosConfig:
    cfg = dict(
        aspect_ratio=a.aspect,
        resolution=a.resolution,
        duration_seconds=a.duration,
        negative_prompt=a.negative,
        number_of_videos=a.count,
        seed=a.seed,
    )
    if getattr(a, "last_frame", None):
        cfg["last_frame"] = load_image(a.last_frame)
    refs = [
        types.VideoGenerationReferenceImage(image=load_image(p), reference_type="ASSET")
        for p in (getattr(a, "ref", None) or [])
    ]
    if refs:
        cfg["reference_images"] = refs
    return types.GenerateVideosConfig(**{k: v for k, v in cfg.items() if v is not None})


def cmd_models(a):
    c = client()  # keep a reference: the pager needs the client to stay open
    for m in c.models.list():
        if "veo" in m.name.lower():
            print(m.name.removeprefix("models/"), "-", m.display_name or "")


def cmd_generate(a):
    c = client()
    source = types.GenerateVideosSource(
        prompt=a.prompt, image=load_image(a.image) if a.image else None
    )
    print(f"Model: {a.model}", file=sys.stderr)
    op = c.models.generate_videos(model=a.model, source=source, config=build_config(a))
    videos = wait(c, op)
    meta = {"model": a.model, "prompt": a.prompt, "image": a.image,
            "last_frame": a.last_frame, "refs": a.ref}
    save(c, videos, a.name or default_name(a.prompt), meta)


def cmd_extend(a):
    sidecar = pathlib.Path(a.clip).with_suffix(".json")
    if not sidecar.exists():
        sys.exit(f"{sidecar} not found: only clips generated by this tool can be extended.")
    uri = json.loads(sidecar.read_text())["video_uri"]
    c = client()
    source = types.GenerateVideosSource(prompt=a.prompt, video=types.Video(uri=uri))
    config = types.GenerateVideosConfig(resolution="720p", number_of_videos=1)
    op = c.models.generate_videos(model=a.model, source=source, config=config)
    videos = wait(c, op)
    name = a.name or pathlib.Path(a.clip).stem + "-ext"
    save(c, videos, name, {"model": a.model, "prompt": a.prompt, "extends": a.clip})


def cmd_stitch(a):
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
        for clip in a.clips:
            f.write(f"file '{pathlib.Path(clip).resolve()}'\n")
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0",
         "-i", f.name, "-c:v", "libx264", "-c:a", "aac", a.out],
        check=True,
    )
    os.unlink(f.name)
    print(a.out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    sub.add_parser("models", help="list available Veo models").set_defaults(fn=cmd_models)

    g = sub.add_parser("generate", help="text/image to video")
    g.add_argument("prompt")
    g.add_argument("--image", help="starting frame image")
    g.add_argument("--last-frame", help="ending frame image (needs --image)")
    g.add_argument("--ref", action="append", help="reference image for a character/object (repeatable, up to 3)")
    g.add_argument("--aspect", choices=["16:9", "9:16"], help="default 16:9")
    g.add_argument("--resolution", choices=["720p", "1080p"])
    g.add_argument("--duration", type=int, help="seconds (model-dependent, e.g. 4, 6 or 8)")
    g.add_argument("--negative", help="what to avoid")
    g.add_argument("--count", type=int, help="number of variations")
    g.add_argument("--seed", type=int)
    g.add_argument("--name", help="output file name (no extension)")
    g.add_argument("--model", default=DEFAULT_MODEL)
    g.set_defaults(fn=cmd_generate)

    e = sub.add_parser("extend", help="continue a generated clip")
    e.add_argument("clip")
    e.add_argument("prompt")
    e.add_argument("--name")
    e.add_argument("--model", default=DEFAULT_MODEL)
    e.set_defaults(fn=cmd_extend)

    s = sub.add_parser("stitch", help="join clips into one video")
    s.add_argument("out")
    s.add_argument("clips", nargs="+")
    s.set_defaults(fn=cmd_stitch)

    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
